import Foundation
import simd

/// One training image: where it is on disk (relative to transforms.json) and the camera that took it.
struct DatasetFrame: Equatable {
  var filePath: String
  var cameraToWorld: simd_float4x4
  var intrinsics: PinholeIntrinsics
}

/// Writes the capture as a Nerfstudio-format dataset that Brush trains from directly:
/// `transforms.json` + images + an optional `points.ply` starting cloud.
enum DatasetWriter {
  /// ARKit's camera-to-world transform already uses the OpenGL camera convention that
  /// `transform_matrix` expects, so poses are written unchanged (row-major).
  static func transformsJSON(frames: [DatasetFrame], plyFilePath: String?) throws -> Data {
    var root: [String: Any] = [
      "camera_model": "PINHOLE",
      "frames": frames.map { frame -> [String: Any] in
        [
          "file_path": frame.filePath,
          "transform_matrix": CaptureMath.rowMajor(frame.cameraToWorld).map { $0.map(Double.init) },
          "fl_x": Double(frame.intrinsics.fx),
          "fl_y": Double(frame.intrinsics.fy),
          "cx": Double(frame.intrinsics.cx),
          "cy": Double(frame.intrinsics.cy),
          "w": frame.intrinsics.width,
          "h": frame.intrinsics.height,
        ]
      },
    ]
    if let plyFilePath { root["ply_file_path"] = plyFilePath }
    return try JSONSerialization.data(withJSONObject: root, options: [.prettyPrinted, .sortedKeys])
  }

  /// Binary little-endian PLY with float x/y/z and uchar red/green/blue per vertex,
  /// which Brush loads as its initial gaussians.
  static func pointCloudPLY(_ points: [ColoredPoint]) -> Data {
    let header = """
      ply
      format binary_little_endian 1.0
      comment generated by soon2026 SplatCapture
      element vertex \(points.count)
      property float x
      property float y
      property float z
      property uchar red
      property uchar green
      property uchar blue
      end_header

      """
    var data = Data(header.utf8)
    data.reserveCapacity(data.count + points.count * 15)
    for point in points {
      for value in [point.position.x, point.position.y, point.position.z] {
        withUnsafeBytes(of: value.bitPattern.littleEndian) { data.append(contentsOf: $0) }
      }
      data.append(contentsOf: [point.color.x, point.color.y, point.color.z])
    }
    return data
  }
}
